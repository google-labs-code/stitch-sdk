import { parseArgs } from "util";
import { mkdir, writeFile } from "fs/promises";
import { join, resolve, basename } from "path";
import { stitch } from "@google/stitch-sdk";

// Parse command line arguments
const { values } = parseArgs({
  args: process.argv.slice(2),
  options: {
    projectId: { type: "string" },
    screenId: { type: "string" },
    prompt: { type: "string" },
    outDir: { type: "string", default: "./out" },
  },
});

async function run() {
  if (!values.prompt && !(values.projectId && values.screenId)) {
    console.error("Must provide either --prompt OR (--projectId AND --screenId)");
    process.exit(1);
  }

  let htmlUrl: string;

  if (values.prompt) {
    console.log(`Generating new project with prompt: "${values.prompt}"...`);
    const { projectId } = await stitch.callTool<{ projectId: string }>("create_project", { title: "Next.js App" });
    const project = stitch.project(projectId);
    console.log(`Created project ${projectId}`);
    const screen = await project.generate(values.prompt);
    console.log(`Generated screen ${screen.id}`);
    htmlUrl = await screen.getHtml();
  } else {
    console.log(`Fetching screen ${values.screenId} from project ${values.projectId}...`);
    const project = stitch.project(values.projectId!);
    const screens = await project.screens();
    const screen = screens.find((s) => s.id === values.screenId) ?? screens[0];
    htmlUrl = await screen.getHtml();
  }

  console.log(`Downloading HTML from ${htmlUrl}...`);
  const response = await fetch(htmlUrl);
  if (!response.ok) {
    throw new Error(`Failed to download HTML: ${response.statusText}`);
  }
  const html = await response.text();


  // Prevent path traversal
  const safeOutDir = resolve(values.outDir!);

  console.log(`Creating output directory ${safeOutDir}...`);
  await mkdir(safeOutDir, { recursive: true });
  await mkdir(join(safeOutDir, "app"), { recursive: true });


  // 1. Extract Tailwind Config
  console.log("Extracting Tailwind config...");
  const configMatch = html.match(/<script id="tailwind-config">([\s\S]*?)<\/script>/);
  let tailwindConfigCode = "import type { Config } from 'tailwindcss';\n\nexport default {\n  content: [\n    './app/**/*.{js,ts,jsx,tsx,mdx}',\n  ],\n  theme: { extend: {} },\n  plugins: [],\n} satisfies Config;";

  if (configMatch) {
    const rawConfig = configMatch[1];
    // Very naive extraction: attempt to grab the object after `tailwind.config = `
    const objMatch = rawConfig.match(/tailwind\.config\s*=\s*({[\s\S]*});/);
    if (objMatch) {
      // Just wrap it in the TS structure
      tailwindConfigCode = `import type { Config } from 'tailwindcss';\n\nconst config: Config = ${objMatch[1]};\nconfig.content = [\n  './app/**/*.{js,ts,jsx,tsx,mdx}',\n];\nexport default config;`;
    }
  }

  await writeFile(join(safeOutDir, "tailwind.config.ts"), tailwindConfigCode);
  console.log("Wrote tailwind.config.ts");


  // 2. Extract Google Fonts
  console.log("Extracting Google Fonts...");
  const fonts = html.match(/<link[^>]*fonts\.googleapis\.com[^>]*>/g) ?? [];
  const fontLinks = fonts.join("\n    ");

  // 3. Extract Body content
  console.log("Extracting HTML body...");
  const bodyMatch = html.match(/<body[^>]*>([\s\S]*?)<\/body>/);
  let bodyContent = bodyMatch ? bodyMatch[1] : html;

  // Convert generic HTML to JSX (naive for this script)
  // class -> className
  bodyContent = bodyContent.replace(/class=/g, "className=");
  // close inputs and img
  bodyContent = bodyContent.replace(/<img([^>]*[^\/])>/g, "<img$1 />");
  bodyContent = bodyContent.replace(/<input([^>]*[^\/])>/g, "<input$1 />");
  bodyContent = bodyContent.replace(/<br>/g, "<br />");
  bodyContent = bodyContent.replace(/<hr([^>]*[^\/])?>/g, "<hr$1 />");
  // remove unescaped script tags from body
  bodyContent = bodyContent.replace(/<script\b[^>]*>[\s\S]*?<\/script\s*[^>]*>/gi, "");

  const pageCode = `export default function Page() {\n  return (\n    <>\n${bodyContent}\n    </>\n  );\n}\n`;
  await writeFile(join(safeOutDir, "app", "page.tsx"), pageCode);
  console.log("Wrote app/page.tsx");


  const layoutCode = `import './globals.css';\n\nexport const metadata = {\n  title: 'Stitch Next.js App',\n  description: 'Generated by @google/stitch-sdk',\n};\n\nexport default function RootLayout({ children }: { children: React.ReactNode }) {\n  return (\n    <html lang="en">\n      <head>\n        ${fontLinks}\n      </head>\n      <body>\n        {children}\n      </body>\n    </html>\n  );\n}\n`;
  await writeFile(join(safeOutDir, "app", "layout.tsx"), layoutCode);
  console.log("Wrote app/layout.tsx");

  const globalsCss = `@tailwind base;\n@tailwind components;\n@tailwind utilities;\n`;
  await writeFile(join(safeOutDir, "app", "globals.css"), globalsCss);
  console.log("Wrote app/globals.css");

  // Next.js config to allow googleusercontent images if they exist
  const nextConfigCode = `/** @type {import('next').NextConfig} */\nconst nextConfig = {\n  images: {\n    remotePatterns: [\n      {\n        protocol: 'https',\n        hostname: 'lh3.googleusercontent.com',\n      },\n      {\n        protocol: 'https',\n        hostname: 'images.unsplash.com',\n      }\n    ],\n  },\n};\n\nmodule.exports = nextConfig;\n`;
  await writeFile(join(safeOutDir, "next.config.js"), nextConfigCode);
  console.log("Wrote next.config.js");


  console.log(`\nDone! Next.js scaffolding written to ${safeOutDir}`);
  console.log("Next steps:");
  console.log(`  cd ${safeOutDir}`);
  console.log("  npm init -y");
  console.log("  npm install next react react-dom tailwindcss postcss autoprefixer");
  console.log("  npx tailwindcss init -p");
  console.log("  npx next dev");
}

run().catch(console.error);
